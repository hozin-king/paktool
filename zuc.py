    b = ZUC(bytes([0x01]) * 16, bytes([0xFF]) * 16)
    ga, gb = a.generate(), b.generate()
    assert [next(ga) for _ in range(16)] == [next(gb) for _ in range(16)]

    # zuc_keystream() konsisten dengan ZUC langsung
    ks = zuc_keystream()
    assert len(ks) == 16 and all(0 <= w <= _M32 for w in ks)
