_MOD = 0x7FFFFFFF  # 2^31 - 1
_M32 = 0xFFFFFFFF


def _rotl31(x, n):
    n %= 31
    return ((x << n) | (x >> (31 - n))) & _MOD


def _add31(a, b):
    s = a + b
    r = (s & _MOD) + (s >> 31)
    return 0 if r == _MOD else r


def _rotl32(x, n):
    n %= 32
    return ((x << n) | (x >> (32 - n))) & _M32


def _l1(x):
    return x ^ _rotl32(x, 2) ^ _rotl32(x, 10) ^ _rotl32(x, 18) ^ _rotl32(x, 24)


def _l2(x):
    return x ^ _rotl32(x, 8) ^ _rotl32(x, 14) ^ _rotl32(x, 22) ^ _rotl32(x, 30)


def _s32(x):
    # byte MSB -> LSB: S0, S1, S0, S1
    return ((_S0[(x >> 24) & 0xFF] << 24) | (_S1[(x >> 16) & 0xFF] << 16)
            | (_S0[(x >> 8) & 0xFF] << 8) | _S1[x & 0xFF])


class ZUC:
    """ZUC-128. generate() menghasilkan word 32-bit (int)."""

    def __init__(self, key: bytes, iv: bytes):
        assert len(key) == 16 and len(iv) == 16
        self.s = [((key[i] << 23) | (_D[i] << 8) | iv[i]) for i in range(16)]
        self.r1 = 0
        self.r2 = 0
        for _ in range(32):
            x0, x1, x2 = self._br()[:3]
            w = self._f(x0, x1, x2)
            self._lfsr_init(w >> 1)
        x0, x1, x2 = self._br()[:3]
        self._f(x0, x1, x2)  # W dibuang
        self._lfsr_work()

    def _br(self):
        s = self.s
        x0 = (((s[15] >> 15) & 0xFFFF) << 16) | (s[14] & 0xFFFF)
        x1 = ((s[11] & 0xFFFF) << 16) | ((s[9] >> 15) & 0xFFFF)
        x2 = ((s[7] & 0xFFFF) << 16) | ((s[5] >> 15) & 0xFFFF)
        x3 = ((s[2] & 0xFFFF) << 16) | ((s[0] >> 15) & 0xFFFF)
        return x0, x1, x2, x3

    def _f(self, x0, x1, x2):
        w = ((x0 ^ self.r1) + self.r2) & _M32
        w1 = (self.r1 + x1) & _M32
        w2 = self.r2 ^ x2
        self.r1 = _s32(_l1(((w1 & 0xFFFF) << 16) | (w2 >> 16)))
        self.r2 = _s32(_l2(((w2 & 0xFFFF) << 16) | (w1 >> 16)))
        return w

    def _step1(self):
        s = self.s
        v = _rotl31(s[15], 15)
        v = _add31(v, _rotl31(s[13], 17))
        v = _add31(v, _rotl31(s[10], 21))
        v = _add31(v, _rotl31(s[4], 20))
        v = _add31(v, _rotl31(s[0], 8))
        v = _add31(v, s[0])
        return v

    def _lfsr_init(self, u):
        v = self._step1()
        if v == 0:
            v = _MOD
        s16 = _add31(v, u)
        if s16 == 0:
            s16 = _MOD
        self.s = self.s[1:] + [s16]

    def _lfsr_work(self):
        v = self._step1()
        if v == 0:
            v = _MOD
        self.s = self.s[1:] + [v]

    def generate(self):
        """Generator: tiap next() satu word keystream 32-bit."""
        while True:
            x0, x1, x2, x3 = self._br()
            w = self._f(x0, x1, x2)
            z = w ^ x3
            self._lfsr_work()
            yield z


def zuc_keystream():
    """16 word keystream untuk footer PUBG Mobile.

    Key = 16 byte 0x01, IV = 16 byte 0xFF (FIXED — sesuai tool referensi).
    """
    z = ZUC(bytes([0x01]) * 16, bytes([0xFF]) * 16)
    g = z.generate()
    return [next(g) for _ in range(16)]


